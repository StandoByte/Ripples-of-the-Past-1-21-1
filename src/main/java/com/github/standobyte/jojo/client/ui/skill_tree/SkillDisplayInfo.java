package com.github.standobyte.jojo.client.ui.skill_tree;

// net.minecraft.advancements.DisplayInfo copypaste
public class SkillDisplayInfo {
	private float x;
	private float y;

	public void setLocation(float x, float y) {
		this.x = x;
		this.y = y;
	}

	public float getX() {
		return this.x;
	}

	public float getY() {
		return this.y;
	}
}
